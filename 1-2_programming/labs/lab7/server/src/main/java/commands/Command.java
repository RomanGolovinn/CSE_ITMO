package commands;

import models.Flat;

/**
 * Базовый интерфейс для всех команд в приложении.
 * Определяет общий контракт: выполнение логики, получение имени и описания команды.
 *
 * @author Roman Golovin
 */
public interface Command {

    /**
     * Выполняет основную логику команды с заданными аргументами.
     *
     * @param argument     строковый аргумент, переданный пользователем вместе с командой (может быть пустым)
     * @param flatArgument объект квартиры, если команда требует ввода сложного элемента (иначе null)
     */
    String execute(String argument, Flat flatArgument);

    /**
     * Возвращает имя команды, по которому она вызывается пользователем из консоли.
     *
     * @return имя команды (например, "add", "help")
     */
    String getName();

    /**
     * Возвращает краткое описание команды для вывода в справке.
     *
     * @return описание действия команды
     */
    String getDescription();
}